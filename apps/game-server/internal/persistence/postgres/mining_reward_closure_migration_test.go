func TestG21ClosureT121G17G18LifecycleWithConsumedReservation(t *testing.T) {
	s, cmd, receipt := g21ConstraintFixture(t)
	ctx := context.Background()
	svc := miningblock.NewService(s, miningblock.DevelopmentRuleVersion, false)
	spend, err := systemspend.NewService(s, g15Registry(t)).Post(ctx, g15Intent("closure-regression-spend", 20))
	if err != nil {
		t.Fatal(err)
	}
	issuance, err := emission.NewService(s, emission.DevelopmentRuleVersion).Apply(ctx, spend.ID)
	if err != nil {
		t.Fatal(err)
	}
	cancelled, err := svc.Create(ctx, "closure-regression-cancel")
	if err != nil {
		t.Fatal(err)
	}
	cancellation, err := svc.Cancel(ctx, cancelled.BlockID)
	if err != nil {
		t.Fatal(err)
	}
	open, err := svc.Create(ctx, "closure-regression-finalize")
	if err != nil {
		t.Fatal(err)
	}
	finalized, err := s.FinalizeMiningBlock(ctx, open.BlockID)
	if err != nil {
		t.Fatal(err)
	}
	refund, err := contribution.NewService(s).RefundSystemSpend(ctx, g15Refund(spend, "closure-regression-refund", 15))
	if err != nil {
		t.Fatal(err)
	}
	if r, e := s.ReconcileBlackIronEmission(ctx); e != nil || !r.Balanced {
		t.Fatalf("extended conservation=%+v %v", r, e)
	}
	snap, err := s.SnapshotBlackIronEmission(ctx)
	if err != nil || snap.Pool.TotalEmissionCapacity != 25 || snap.Pool.TotalReserved != 10 || snap.Pool.TotalDistributed != 10 || snap.Pool.RemainingCapacity != 5 || snap.Pool.RecoveryDebt != 0 {
		t.Fatalf("C/S/D/M/H=%+v %v", snap.Pool, err)
	}
	before := g21ClosureSnapshot(t, s)
	if r, e := emission.NewService(s, emission.DevelopmentRuleVersion).Apply(ctx, spend.ID); e != nil || !reflect.DeepEqual(r, issuance) {
		t.Fatalf("G17 replay=%+v %v", r, e)
	}
	if r, e := svc.Cancel(ctx, cancelled.BlockID); e != nil || !reflect.DeepEqual(r, cancellation) {
		t.Fatalf("G18 cancel replay=%+v %v", r, e)
	}
	if r, e := s.FinalizeMiningBlock(ctx, open.BlockID); e != nil || !reflect.DeepEqual(r, finalized) {
		t.Fatalf("G18 finalize replay=%+v %v", r, e)
	}
	if r, e := contribution.NewService(s).RefundSystemSpend(ctx, g15Refund(spend, "closure-regression-refund", 15)); e != nil || !reflect.DeepEqual(r, refund) {
		t.Fatalf("refund replay=%+v %v", r, e)
	}
	if r, e := s.SettleMiningRewardTEST(ctx, cmd); e != nil || !reflect.DeepEqual(r, receipt) {
		t.Fatalf("G21 replay=%+v %v", r, e)
	}
	if before != g21ClosureSnapshot(t, s) {
		t.Fatal("cross-version replay changed persisted history")
	}
	t.Log(fmt.Sprintf("C25=S10+D10+M5-H0, FINAL=%s", receipt.SettlementID))
}
